/**
 * ZCDC 日志开关（2026-10-15）。
 *
 * 之前每个临时诊断点各自定义一个模块私有开关（`ZC_CAPTURE_DIAGNOSTICS` /
 * `ZC_WALL_DIAGNOSTICS`），想静音得逐个文件去改、还漏得掉；这里收成**唯一真源**，
 * 一次性关掉 zcds 整片的日志噪音。
 *
 * 两档口径（分档是因为「诊断噪音」和「真错线索」的可丢程度不同）：
 * - `ZCDC_LOG_DIAGNOSTICS`：**逐帧 / 高频定位用**的诊断日志。默认关。它挂在渲染与模拟的
 *   每帧路径上，一次开局能刷几百行（截图里那批 `[ZCCapture] 有我方兵但未占领` 就是），
 *   开着会把真问题埋掉。定位完就删代码 + 关常量。
 * - `ZCDC_LOG_WARNINGS`：**一次性的加载失败 / 资源缺失 / 配置缺失**告警。默认开。
 *   关掉会让「美术没交 / 路径打错」静默降级，归因不到，所以不跟诊断同档。
 *
 * 🔴 判据：`tests/zcds-log-switch.test.ts` 用 AST 断言 zcds 下每条 `console.*`
 * 都落在这两个开关的作用域内（不靠正则数括号 ⇒ 注释里的示例、中文字符串、
 * 模板字符串跨行拼接都不会误判）。新增 zcds 日志**必须**挂开关，否则那条红。
 */
export const ZCDC_LOG_DIAGNOSTICS = false;

/** 加载失败 / 资源缺失 / 配置缺失告警；默认开，定位完可以不关（它不打在每帧路径上）。 */
export const ZCDC_LOG_WARNINGS = true;
