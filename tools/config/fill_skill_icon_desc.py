def main():
    wb = load_workbook(PATH)
    ws = wb['技能说明']
    head = ws.cell(row=1, column=COL_DESC).value
    assert head == '技能描述', head

    done, skipped = 0, []
    for row in range(2, ws.max_row + 1):
        idx = ws.cell(row=row, column=1).value
        if not isinstance(idx, int):
            continue
        if idx in DESC:
            ws.cell(row=row, column=COL_DESC).value = DESC[idx]
            done += 1
        else:
            skipped.append((idx, ws.cell(row=row, column=2).value,
                            ws.cell(row=row, column=3).value,
                            ws.cell(row=row, column=COL_DESC).value))
    wb.save(PATH)
    print('写入', done, '条；保留原稿', len(skipped), '条')
    for s in skipped:
        print('  保留', s)


if __name__ == '__main__':
    main()
