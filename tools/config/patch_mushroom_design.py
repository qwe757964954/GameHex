def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    check = not args.write

    xml = read_zip_rows(DESIGN, SHEET)

    # ① 表头 S1 补第四态
    xml = put_cell(xml, 'S1', HEADER_S) if not check else xml
    print('S1 = %s' % HEADER_S)

    # ② 每卡四列（B / E / Q / R）
    card_cells = 0
    for row, cid in sorted(ROW_CARD.items()):
        card = CARDS[cid]
        pairs = [('B', card['name']), ('E', card['role']),
                 ('Q', card['counter']), ('R', card['countered'])]
        for col, value in pairs:
            if not check:
                xml = set_cell_safe(xml, '%s%d' % (col, row), value)
            card_cells += 1
    print('卡头四列：%d 行 × 4 = %d 格' % (len(ROW_CARD), card_cells))

    # ③ 逐行覆盖
    detail_cells = 0
    for row in sorted(ROWS):
        for col, value in sorted(ROWS[row].items()):
            if not check:
                xml = put_cell(xml, '%s%d' % (col, row), value)
            detail_cells += 1
    print('技能行覆盖：%d 行 = %d 格' % (len(ROWS), detail_cells))

    if check:
        for row in sorted(ROWS):
            cid = ROW_CARD[row]
            print('  行%d %s %-6s %-10s %s' % (
                row, cid, CARDS[cid]['name'],
                (ROWS[row].get('H') or '（沿用）'), ROWS[row].get('S') or '（沿用）'))
        print('== 干跑完成，未落盘 ==')
        return 0

    write_zip(DESIGN, SHEET, xml, BACKUP)
    print('== 已写入 %s ==' % os.path.basename(DESIGN))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
