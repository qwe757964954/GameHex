def _n(text, pat):
    m = re.search(pat, text or '')
    return float(m.group(1)) if m else 0.0


TAIL_ONE = r'(?:攻击提高|伤害提高|攻击速度提高|攻击范围提高|最大生命提高)\s*\d+%'
TAIL_RE = re.compile(r'；(?:' + TAIL_ONE + r')(?:，(?:' + TAIL_ONE + r'))*$')
TAIL_W = {'攻击提高': 1.0, '伤害提高': 1.2, '攻击速度提高': 0.95,
          '攻击范围提高': 0.7, '最大生命提高': 1.0}


def split_tail(full):
    """把「；攻击提高 X%，伤害提高 Y%」尾巴切掉（尾巴是纯词缀列表，主文案不会以它结尾）。"""
    for m in re.finditer('；', full):
        if TAIL_RE.fullmatch(full[m.start():]):
            return full[:m.start()], full[m.start():]
    return full, ''


def tail_vp(seg):
    return sum(_n(seg, k + r'\s*(\d+)%') * w for k, w in TAIL_W.items())


