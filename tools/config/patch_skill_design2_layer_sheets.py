def truncate_from(xml, marker):
    """删掉含 marker 的那一行及其之后的所有行（重跑时先清掉上一轮追加的块，保证幂等）。"""
    hit = None
    for m in re.finditer(r'<row r="(\d+)"[^>]*>(.*?)</row>', xml, re.S):
        if marker in m.group(2):
            hit = (int(m.group(1)), m.start())
            break
    if hit is None:
        return xml, None
    start_row, pos = hit
    #  追加时前面留了一个空行，一并吃掉，避免多次重跑累积空行
    prev = re.search(r'<row r="%d"[^>]*>(.*?)</row>' % (start_row - 1), xml, re.S)
    if prev is not None and '<c ' not in prev.group(1):
        pos, start_row = prev.start(), start_row - 1
    return xml[:pos] + '</sheetData>' + xml.split('</sheetData>', 1)[1], start_row


def append(xml, start_row, table, styles_row, gap=1):
    """在 sheetData 末尾追加 table（list of list）。styles 借用 styles_row 的逐列样式。"""
    styles = styles_of_row(xml, styles_row)
    head = last_data_row(xml) + gap
    add = ''
    for i, vals in enumerate(table):
        r = head + i
        cells = ''.join(cell_xml('%s%d' % (col_letter(j), r), styles.get(col_letter(j)), v)
                        for j, v in enumerate(vals) if v is not None)
        add += '<row r="%d">%s</row>' % (r, cells)
    xml = xml.replace('</sheetData>', add + '</sheetData>', 1)
    return bump_dimension(xml, head + len(table)), head


