        if not v:
            continue
        m = sum(v) / len(v)
        mean[rar] = m
        n = sum(1 for r in rows if r[4] == rar)
        t.append([rar[0], len(v), n, round(m, 1), BUD[rar],
                  '%d%%' % round(100 * m / BUD[rar]), note[rar], None])
